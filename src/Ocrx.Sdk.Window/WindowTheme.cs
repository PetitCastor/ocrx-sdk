namespace Ocrx.Sdk.Window;

/// <summary>The colours of a plugin window and its title bar.</summary>
public enum WindowTheme
{
    /// <summary>Follows the Windows app mode (Settings, Personalization, Colors), and changes with it.</summary>
    System,

    /// <summary>Always light.</summary>
    Light,

    /// <summary>Always dark.</summary>
    Dark,
}
